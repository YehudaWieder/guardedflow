// Generates frontend/src/generated/*.ts from the JSON Schema that the backend
// exports for each Pydantic model in app.core.schemas. Never edit the output
// by hand — re-run this script after changing a schema.
import { execFileSync } from "node:child_process";
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { compile } from "json-schema-to-typescript";
import { tmpdir } from "node:os";
import { join } from "node:path";

const BACKEND_DIR = new URL("../../backend", import.meta.url).pathname;
const OUT_DIR = new URL("../src/generated", import.meta.url).pathname;
const SCHEMA_DIR = join(tmpdir(), "guardedflow-schemas");

rmSync(SCHEMA_DIR, { recursive: true, force: true });
mkdirSync(SCHEMA_DIR, { recursive: true });

execFileSync(
  "uv",
  ["run", "python", "-m", "app.core.schemas.export_json_schema", SCHEMA_DIR],
  { cwd: BACKEND_DIR, stdio: "inherit" },
);

mkdirSync(OUT_DIR, { recursive: true });

for (const file of readdirSync(SCHEMA_DIR).filter((f) => f.endsWith(".json"))) {
  const schema = JSON.parse(readFileSync(join(SCHEMA_DIR, file), "utf-8"));
  const ts = await compile(schema, schema.title, { bannerComment: "" });
  const outName = file.replace(/\.json$/, ".ts");
  writeFileSync(
    join(OUT_DIR, outName),
    `// Generated by \`pnpm gen:types\` from app.core.schemas.${schema.title}. Do not edit by hand.\n\n${ts}`,
  );
  console.log(`wrote src/generated/${outName}`);
}
